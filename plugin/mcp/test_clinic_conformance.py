def test_trigger_coverage():
    trigger_map = {'find-doctor': ['find a doctor', 'cardiologist available', 'doctor on monday'], 'book-appointment': ['book an appointment', 'see dr ahmed tomorrow'], 'reschedule-appointment': ['move my appointment', 'reschedule visit'], 'cancel-appointment': ['cancel my appointment', 'cannot come tomorrow']}
    assert len(trigger_map) > 0
    for skill, triggers in trigger_map.items():
        assert len(triggers) >= 1, skill
        assert all(t.strip() for t in triggers), skill


def test_escalation_tiers_valid():
    tiers = ['auto', 'confirm', 'human_only']
    assert set(tiers) <= {"auto", "confirm", "human_only"}
    assert len(tiers) > 0

